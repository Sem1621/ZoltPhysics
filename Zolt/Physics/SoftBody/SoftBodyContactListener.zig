//! Port of: Jolt/Physics/SoftBody/SoftBodyContactListener.h
//! Status: complete
//!
//! `SoftBodyContactListener` is an interface (porting guide pattern B, SimulationArchitecture D7): a type erased
//! `ptr: *anyopaque` (the callbacks are non-const in Jolt) and a vtable with a nullable entry per callback. Both
//! callbacks have a default implementation in Jolt, so an implementation only declares the ones it needs; a missing
//! one behaves like Jolt's default. The callbacks run concurrently on the job system's worker threads.
//! `SoftBodyContactSettings.is_sensor` is uninitialized in Jolt (`undefined` here); the system fills it in.

const std = @import("std");
const Body = @import("../Body/Body.zig").Body;
const SoftBodyManifold = @import("SoftBodyManifold.zig").SoftBodyManifold;

/// Return value for the OnSoftBodyContactValidate callback. Determines if the contact will be processed or not.
pub const SoftBodyValidateResult = enum {
    /// Accept this contact
    accept_contact,
    /// Reject this contact
    reject_contact,
};

/// Contact settings for a soft body contact.
/// The values are filled in with their defaults by the system so the callback doesn't need to modify anything, but it can if it wants to.
pub const SoftBodyContactSettings = struct {
    /// Scale factor for the inverse mass of the soft body (0 = infinite mass, 1 = use original mass, 2 = body has half the mass). For the same contact pair, you should strive to keep the value the same over time.
    inv_mass_scale1: f32 = 1.0,
    /// Scale factor for the inverse mass of the other body (0 = infinite mass, 1 = use original mass, 2 = body has half the mass). For the same contact pair, you should strive to keep the value the same over time.
    inv_mass_scale2: f32 = 1.0,
    /// Scale factor for the inverse inertia of the other body (usually same as mInvMassScale2)
    inv_inertia_scale2: f32 = 1.0,
    /// If the contact should be treated as a sensor vs body contact (no collision response)
    is_sensor: bool = undefined,
};

/// A listener class that receives collision contact events for soft bodies against rigid bodies.
/// It can be registered with the PhysicsSystem.
pub const SoftBodyContactListener = struct {
    ptr: *anyopaque,
    vtable: *const VTable,

    /// One nullable entry per callback: null is Jolt's default implementation
    pub const VTable = struct {
        /// Called whenever the soft body's aabox overlaps with another body's aabox (so receiving this callback doesn't tell if any of the vertices will collide).
        /// This callback can be used to change the behavior of the collision response for all vertices in the soft body or to completely reject the contact.
        /// Note that this callback is called when all bodies are locked, so don't use any locking functions!
        /// @param soft_body The soft body that collided. It is safe to access this as the soft body is only updated on the current thread.
        /// @param other_body The other body that collided. Note that accessing the position/orientation/velocity of other_body may result in a race condition as other threads may be modifying the body at the same time.
        /// @param settings The settings for all contact points that are generated by this collision.
        /// @return Whether the contact should be processed or not.
        onSoftBodyContactValidate: ?*const fn (ptr: *anyopaque, soft_body: *const Body, other_body: *const Body, settings: *SoftBodyContactSettings) SoftBodyValidateResult = null,

        /// Called after all contact points for a soft body have been handled.
        /// Note that this callback is called when all bodies are locked, so don't use any locking functions!
        /// You will receive a single callback for a soft body per simulation step for performance reasons, this callback will apply to all vertices in the soft body.
        /// @param soft_body The soft body that collided. It is safe to access this as the soft body is only updated on the current thread.
        /// @param manifold The manifold that describes which vertices collide and with what body they collide. Other bodies may be modified by other threads during this callback.
        onSoftBodyContactAdded: ?*const fn (ptr: *anyopaque, soft_body: *const Body, manifold: *const SoftBodyManifold) void = null,
    };

    /// Wrap any `*T` that declares some of the callbacks
    pub fn init(impl: anytype) SoftBodyContactListener {
        const T = @typeInfo(@TypeOf(impl)).pointer.child;
        const gen = struct {
            // Thunks need their own names: Zig forbids shadowing the functions of the outer struct
            fn onSoftBodyContactValidateThunk(ptr: *anyopaque, soft_body: *const Body, other_body: *const Body, settings: *SoftBodyContactSettings) SoftBodyValidateResult {
                const self: *T = @ptrCast(@alignCast(ptr));
                return self.onSoftBodyContactValidate(soft_body, other_body, settings);
            }

            fn onSoftBodyContactAddedThunk(ptr: *anyopaque, soft_body: *const Body, manifold: *const SoftBodyManifold) void {
                const self: *T = @ptrCast(@alignCast(ptr));
                self.onSoftBodyContactAdded(soft_body, manifold);
            }

            const vtable: VTable = .{
                .onSoftBodyContactValidate = if (@hasDecl(T, "onSoftBodyContactValidate")) onSoftBodyContactValidateThunk else null,
                .onSoftBodyContactAdded = if (@hasDecl(T, "onSoftBodyContactAdded")) onSoftBodyContactAddedThunk else null,
            };
        };
        return .{ .ptr = impl, .vtable = &gen.vtable };
    }

    /// See VTable.onSoftBodyContactValidate (default: accept the contact)
    pub fn onSoftBodyContactValidate(self: SoftBodyContactListener, soft_body: *const Body, other_body: *const Body, settings: *SoftBodyContactSettings) SoftBodyValidateResult {
        if (self.vtable.onSoftBodyContactValidate) |f|
            return f(self.ptr, soft_body, other_body, settings);
        return .accept_contact;
    }

    /// See VTable.onSoftBodyContactAdded (default: do nothing)
    pub fn onSoftBodyContactAdded(self: SoftBodyContactListener, soft_body: *const Body, manifold: *const SoftBodyManifold) void {
        if (self.vtable.onSoftBodyContactAdded) |f|
            f(self.ptr, soft_body, manifold);
    }
};

test "SoftBodyContactListener: defaults and an implementation" {
    const expect = std.testing.expect;
    const body1: Body = .{ .id = .init(1) };
    const body2: Body = .{ .id = .init(2) };
    var settings: SoftBodyContactSettings = .{ .is_sensor = false };
    try expect(settings.inv_mass_scale1 == 1.0 and settings.inv_mass_scale2 == 1.0 and settings.inv_inertia_scale2 == 1.0);
    const empty_manifold: SoftBodyManifold = .{ .vertices = &.{}, .colliding_shapes = &.{}, .colliding_sensors = &.{} };
    const manifold = &empty_manifold; // Only passed through

    const Nothing = struct {};
    var nothing: Nothing = .{};
    const default_listener = SoftBodyContactListener.init(&nothing);
    try expect(default_listener.vtable.onSoftBodyContactValidate == null);
    try std.testing.expectEqual(SoftBodyValidateResult.accept_contact, default_listener.onSoftBodyContactValidate(&body1, &body2, &settings));
    default_listener.onSoftBodyContactAdded(&body1, manifold);

    const Rejecting = struct {
        added: u32 = 0,
        pub fn onSoftBodyContactValidate(self: *@This(), soft_body: *const Body, other_body: *const Body, s: *SoftBodyContactSettings) SoftBodyValidateResult {
            _ = .{ self, soft_body };
            s.is_sensor = true;
            return if (other_body.getID().eql(.init(2))) .reject_contact else .accept_contact;
        }
        pub fn onSoftBodyContactAdded(self: *@This(), soft_body: *const Body, m: *const SoftBodyManifold) void {
            _ = .{ soft_body, m };
            self.added += 1;
        }
    };
    var rejecting: Rejecting = .{};
    const listener = SoftBodyContactListener.init(&rejecting);
    try std.testing.expectEqual(SoftBodyValidateResult.reject_contact, listener.onSoftBodyContactValidate(&body1, &body2, &settings));
    try expect(settings.is_sensor);
    try std.testing.expectEqual(SoftBodyValidateResult.accept_contact, listener.onSoftBodyContactValidate(&body2, &body1, &settings));
    listener.onSoftBodyContactAdded(&body1, manifold);
    try std.testing.expectEqual(@as(u32, 1), rejecting.added);
}
